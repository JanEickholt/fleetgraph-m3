#!/usr/bin/env python3
"""Generate the lab-floor world, its Nav2 occupancy map and the locations
registry from ONE spec (below), so Gazebo geometry, map and named places
can never drift apart.

Outputs (committed, regenerate after editing the spec):
  src/fleetgraph_sim/worlds/lab_floor.sdf
  src/fleetgraph_sim/maps/lab_floor.pgm + lab_floor.yaml
  src/fleetgraph_sim/config/locations.yaml

Usage: python3 tools/gen_world.py           # regenerate
       python3 tools/gen_world.py --check   # verify outputs are current (pre-commit)
Frames: Gazebo world frame == ROS "map" frame (robot spawns at dock).
"""
import math
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
PKG = os.path.join(ROOT, 'src', 'fleetgraph_sim')

WORLD = 'lab_floor'
WALL_THICKNESS = 0.10     # m
WALL_HEIGHT = 0.60        # m; lidar sits at ~0.13 m
MAP_RESOLUTION = 0.05     # m/px
MAP_X_RANGE = (-1.5, 9.5)     # map extent (m)
MAP_Y_RANGE = (-3.5, 3.5)

# PGM pixel values (Nav2 trinary map)
PIXEL_FREE = 254
PIXEL_OCCUPIED = 0
PIXEL_UNKNOWN = 205

# Floor plan: hall x in [-1, 4], two labs x in [4, 9] split at y = 0.
# Doors (1.0 m) from the hall into lab_1 (y = +1.5) and lab_2 (y = -1.5).
# Each wall: (start_x, start_y, end_x, end_y), axis-aligned centre line.
WALLS = [
    (-1.0, -3.0, 9.0, -3.0),   # south outer
    (-1.0, 3.0, 9.0, 3.0),     # north outer
    (-1.0, -3.0, -1.0, 3.0),   # west outer
    (9.0, -3.0, 9.0, 3.0),     # east outer
    (4.0, 2.0, 4.0, 3.0),      # hall/lab wall, north of lab_1 door
    (4.0, -1.0, 4.0, 1.0),     # hall/lab wall, between the doors
    (4.0, -3.0, 4.0, -2.0),    # hall/lab wall, south of lab_2 door
    (4.0, 0.0, 9.0, 0.0),      # lab_1 / lab_2 separator
]

# Static obstacles: (name, x, y, size_x, size_y, height, in_map).
# in_map False = unknown to the static map: Nav2 must see it with the lidar
# and plan around it (local perception / replanning test).
OBSTACLES = [
    ('shelf', 1.5, 2.6, 1.6, 0.6, 1.2, True),    # storage shelf, north hall wall
    ('table_lab1', 7.5, 2.0, 1.2, 0.8, 0.75, True),
    ('crate', 2.5, 0.8, 0.4, 0.4, 0.5, False),   # on the dock -> lab_1 straight line
]

# Named places (registry ids are the contract's Location.id values).
LOCATIONS = [
    ('dock', 'Charging dock', 0.0, 0.0, 0.0),
    ('storage', 'Storage', 1.5, 1.5, math.pi / 2),
    ('hall', 'Hall', 2.0, -1.5, 0.0),
    ('lab_1', 'Laboratory 1', 6.0, 1.2, 0.0),
    ('lab_2', 'Laboratory 2', 6.5, -1.5, 0.0),
]


def box_model(name, x, y, size_x, size_y, height, rgba):
    size = f'{size_x:.3f} {size_y:.3f} {height:.3f}'
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} {height / 2:.3f} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry><box><size>{size}</size></box></geometry></collision>
        <visual name="visual"><geometry><box><size>{size}</size></box></geometry>
          <material><ambient>{rgba}</ambient><diffuse>{rgba}</diffuse></material></visual>
      </link>
    </model>"""


def wall_boxes():
    """Wall centre lines -> (center_x, center_y, size_x, size_y) boxes of
    thickness WALL_THICKNESS."""
    boxes = []
    for start_x, start_y, end_x, end_y in WALLS:
        center_x, center_y = (start_x + end_x) / 2, (start_y + end_y) / 2
        size_x = abs(end_x - start_x) + WALL_THICKNESS
        size_y = abs(end_y - start_y) + WALL_THICKNESS
        boxes.append((center_x, center_y, size_x, size_y))
    return boxes


def render_sdf():
    models = []
    for index, (center_x, center_y, size_x, size_y) in enumerate(wall_boxes()):
        models.append(box_model(f'wall_{index}', center_x, center_y, size_x, size_y,
                                WALL_HEIGHT, '0.7 0.7 0.7 1'))
    for name, x, y, size_x, size_y, height, _ in OBSTACLES:
        models.append(box_model(name, x, y, size_x, size_y, height, '0.8 0.3 0.1 1'))
    sdf = f"""<?xml version="1.0" ?>
<!-- GENERATED by tools/gen_world.py — edit the spec there, not this file. -->
<sdf version="1.8">
  <world name="{WORLD}">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <light name="sun" type="directional">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry>
          <surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface></collision>
        <visual name="visual"><geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry>
          <material><ambient>0.8 0.8 0.8 1</ambient><diffuse>0.8 0.8 0.8 1</diffuse></material></visual>
      </link>
    </model>{''.join(models)}
  </world>
</sdf>
"""
    return [(os.path.join(PKG, 'worlds', f'{WORLD}.sdf'), sdf.encode())]


def _cell_center_x(col):
    return MAP_X_RANGE[0] + (col + 0.5) * MAP_RESOLUTION


def _cell_center_y(row):
    return MAP_Y_RANGE[1] - (row + 0.5) * MAP_RESOLUTION     # PGM row 0 = top = max y


def render_map():
    width = round((MAP_X_RANGE[1] - MAP_X_RANGE[0]) / MAP_RESOLUTION)
    height = round((MAP_Y_RANGE[1] - MAP_Y_RANGE[0]) / MAP_RESOLUTION)
    grid = [[PIXEL_FREE] * width for _ in range(height)]
    boxes = list(wall_boxes())
    boxes += [(x, y, size_x, size_y)
              for _, x, y, size_x, size_y, _, in_map in OBSTACLES if in_map]
    for center_x, center_y, size_x, size_y in boxes:
        for row in range(height):
            if abs(_cell_center_y(row) - center_y) > size_y / 2:
                continue
            for col in range(width):
                if abs(_cell_center_x(col) - center_x) <= size_x / 2:
                    grid[row][col] = PIXEL_OCCUPIED
    # outside the building: unknown, so planners never route there
    half_wall = WALL_THICKNESS / 2
    for row in range(height):
        y = _cell_center_y(row)
        for col in range(width):
            x = _cell_center_x(col)
            inside = (-1.0 - half_wall <= x <= 9.0 + half_wall and
                      -3.0 - half_wall <= y <= 3.0 + half_wall)
            if not inside:
                grid[row][col] = PIXEL_UNKNOWN
    maps_dir = os.path.join(PKG, 'maps')
    pgm = f'P5\n# generated by tools/gen_world.py\n{width} {height}\n255\n'.encode() + \
        bytes(pixel for row in grid for pixel in row)
    map_yaml = f"""# GENERATED by tools/gen_world.py
image: {WORLD}.pgm
mode: trinary
resolution: {MAP_RESOLUTION}
origin: [{MAP_X_RANGE[0]}, {MAP_Y_RANGE[0]}, 0.0]
negate: 0
occupied_thresh: 0.65
free_thresh: 0.25
"""
    return [(os.path.join(maps_dir, f'{WORLD}.pgm'), pgm),
            (os.path.join(maps_dir, f'{WORLD}.yaml'), map_yaml.encode())]


def render_locations():
    lines = ['# GENERATED by tools/gen_world.py — shared location registry (contract:',
             '# Location.id). Frame: map. yaw in radians.',
             f'world: {WORLD}', 'frame_id: map', 'locations:']
    for location_id, label, x, y, yaw in LOCATIONS:
        lines.append(f'  {location_id}: {{label: "{label}", x: {x}, y: {y}, yaw: {yaw:.4f}}}')
    path = os.path.join(PKG, 'config', 'locations.yaml')
    return [(path, ('\n'.join(lines) + '\n').encode())]


def main(argv):
    """Write the outputs, or with --check only verify they are up to date
    (exit 1 listing stale files; used by the pre-commit hook)."""
    outputs = render_sdf() + render_map() + render_locations()
    if '--check' in argv:
        stale = []
        for path, data in outputs:
            try:
                with open(path, 'rb') as file:
                    current = file.read()
            except OSError:
                current = None
            if current != data:
                stale.append(os.path.relpath(path, ROOT))
        for stale_path in stale:
            print(f'stale generated file: {stale_path} (run python3 tools/gen_world.py)')
        return 1 if stale else 0
    for path, data in outputs:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'wb') as file:
            file.write(data)
        print('wrote', os.path.relpath(path, ROOT))
    return 0


if __name__ == '__main__':
    import sys
    sys.exit(main(sys.argv[1:]))
