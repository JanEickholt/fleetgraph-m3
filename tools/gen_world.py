#!/usr/bin/env python3
"""Generate the lab-floor world, its Nav2 occupancy map and the locations
registry from ONE spec (below), so Gazebo geometry, map and named places
can never drift apart.

Outputs (committed, regenerate after editing the spec):
  src/fleetgraph_sim/worlds/lab_floor.sdf
  src/fleetgraph_sim/maps/lab_floor.pgm + lab_floor.yaml
  src/fleetgraph_sim/config/locations.yaml

Usage: python3 tools/gen_world.py
Frames: Gazebo world frame == ROS "map" frame (robot spawns at dock).
"""
import math
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
PKG = os.path.join(ROOT, 'src', 'fleetgraph_sim')

WORLD = 'lab_floor'
WALL_T = 0.10         # wall thickness (m)
WALL_H = 0.60         # wall height (m); lidar sits at ~0.13 m
RES = 0.05            # map resolution (m/px)
MAP_X = (-1.5, 9.5)   # map extent (m)
MAP_Y = (-3.5, 3.5)

# Floor plan: hall x in [-1, 4], two labs x in [4, 9] split at y = 0.
# Doors (1.0 m) from the hall into lab_1 (y = +1.5) and lab_2 (y = -1.5).
# Each wall: (x0, y0, x1, y1), axis-aligned centre line.
WALLS = [
    (-1.0, -3.0, 9.0, -3.0),   # south outer
    (-1.0, 3.0, 9.0, 3.0),     # north outer
    (-1.0, -3.0, -1.0, 3.0),   # west outer
    (9.0, -3.0, 9.0, 3.0),     # east outer
    (4.0, 2.0, 4.0, 3.0),      # hall/lab wall, north of lab_1 door
    (4.0, -1.0, 4.0, 1.0),     # hall/lab wall, between the doors
    (4.0, -3.0, 4.0, -2.0),    # hall/lab wall, south of lab_2 door
    (4.0, 0.0, 9.0, 0.0),      # lab_1 / lab_2 separator
]

# Static obstacles: (name, x, y, size_x, size_y, height, in_map).
# in_map False = unknown to the static map: Nav2 must see it with the lidar
# and plan around it (local perception / replanning test).
OBSTACLES = [
    ('shelf', 1.5, 2.6, 1.6, 0.6, 1.2, True),    # storage shelf, north hall wall
    ('table_lab1', 7.5, 2.0, 1.2, 0.8, 0.75, True),
    ('crate', 2.5, 0.8, 0.4, 0.4, 0.5, False),   # on the dock -> lab_1 straight line
]

# Named places (registry ids are the contract's Location.id values).
LOCATIONS = [
    ('dock', 'Charging dock', 0.0, 0.0, 0.0),
    ('storage', 'Storage', 1.5, 1.5, math.pi / 2),
    ('hall', 'Hall', 2.0, -1.5, 0.0),
    ('lab_1', 'Laboratory 1', 6.0, 1.2, 0.0),
    ('lab_2', 'Laboratory 2', 6.5, -1.5, 0.0),
]


def box_model(name, x, y, sx, sy, h, rgba):
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} {h / 2:.3f} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry><box><size>{sx:.3f} {sy:.3f} {h:.3f}</size></box></geometry></collision>
        <visual name="visual"><geometry><box><size>{sx:.3f} {sy:.3f} {h:.3f}</size></box></geometry>
          <material><ambient>{rgba}</ambient><diffuse>{rgba}</diffuse></material></visual>
      </link>
    </model>"""


def wall_boxes():
    """Wall centre lines -> (cx, cy, sx, sy) boxes of thickness WALL_T."""
    out = []
    for x0, y0, x1, y1 in WALLS:
        cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
        sx = abs(x1 - x0) + WALL_T
        sy = abs(y1 - y0) + WALL_T
        out.append((cx, cy, sx, sy))
    return out


def write_sdf():
    models = []
    for i, (cx, cy, sx, sy) in enumerate(wall_boxes()):
        models.append(box_model(f'wall_{i}', cx, cy, sx, sy, WALL_H, '0.7 0.7 0.7 1'))
    for name, x, y, sx, sy, h, _ in OBSTACLES:
        models.append(box_model(name, x, y, sx, sy, h, '0.8 0.3 0.1 1'))
    sdf = f"""<?xml version="1.0" ?>
<!-- GENERATED by tools/gen_world.py — edit the spec there, not this file. -->
<sdf version="1.8">
  <world name="{WORLD}">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <light name="sun" type="directional">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry>
          <surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface></collision>
        <visual name="visual"><geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry>
          <material><ambient>0.8 0.8 0.8 1</ambient><diffuse>0.8 0.8 0.8 1</diffuse></material></visual>
      </link>
    </model>{''.join(models)}
  </world>
</sdf>
"""
    path = os.path.join(PKG, 'worlds', f'{WORLD}.sdf')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(sdf)
    return path


def write_map():
    w = round((MAP_X[1] - MAP_X[0]) / RES)
    h = round((MAP_Y[1] - MAP_Y[0]) / RES)
    grid = [[254] * w for _ in range(h)]          # 254 = free
    rects = list(wall_boxes())
    rects += [(x, y, sx, sy) for _, x, y, sx, sy, _, in_map in OBSTACLES if in_map]
    for cx, cy, sx, sy in rects:
        for row in range(h):
            # PGM row 0 = top = max y
            y = MAP_Y[1] - (row + 0.5) * RES
            if abs(y - cy) > sy / 2:
                continue
            for col in range(w):
                x = MAP_X[0] + (col + 0.5) * RES
                if abs(x - cx) <= sx / 2:
                    grid[row][col] = 0             # occupied
    # outside the building: unknown (205), so planners never route there
    for row in range(h):
        y = MAP_Y[1] - (row + 0.5) * RES
        for col in range(w):
            x = MAP_X[0] + (col + 0.5) * RES
            inside = (-1.0 - WALL_T / 2 <= x <= 9.0 + WALL_T / 2 and
                      -3.0 - WALL_T / 2 <= y <= 3.0 + WALL_T / 2)
            if not inside:
                grid[row][col] = 205
    maps = os.path.join(PKG, 'maps')
    os.makedirs(maps, exist_ok=True)
    with open(os.path.join(maps, f'{WORLD}.pgm'), 'wb') as f:
        f.write(f'P5\n# generated by tools/gen_world.py\n{w} {h}\n255\n'.encode())
        f.write(bytes(v for row in grid for v in row))
    with open(os.path.join(maps, f'{WORLD}.yaml'), 'w') as f:
        f.write(f"""# GENERATED by tools/gen_world.py
image: {WORLD}.pgm
mode: trinary
resolution: {RES}
origin: [{MAP_X[0]}, {MAP_Y[0]}, 0.0]
negate: 0
occupied_thresh: 0.65
free_thresh: 0.25
""")
    return w, h


def write_locations():
    path = os.path.join(PKG, 'config', 'locations.yaml')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    lines = ['# GENERATED by tools/gen_world.py — shared location registry (contract:',
             '# Location.id). Frame: map. yaw in radians.',
             f'world: {WORLD}', 'frame_id: map', 'locations:']
    for lid, label, x, y, yaw in LOCATIONS:
        lines.append(f'  {lid}: {{label: "{label}", x: {x}, y: {y}, yaw: {yaw:.4f}}}')
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    return path


if __name__ == '__main__':
    print('world:', write_sdf())
    print('map px:', write_map())
    print('locations:', write_locations())
